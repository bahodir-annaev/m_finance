def get_text(lang, key, *args):
    """Translated string for key, or the key itself when it is missing."""
    table = TRANSLATIONS.get(lang) or TRANSLATIONS['uz']
    text = table.get(key)
    if text is None:
        text = TRANSLATIONS['uz'].get(key, key)
    if args:
        try:
            return text.format(*args)
        except (IndexError, KeyError):
            return text
    return text


def missing_keys(lang):
    """Keys present in the Uzbek reference but absent from `lang`."""
    reference = set(TRANSLATIONS['uz'])
    return sorted(reference - set(TRANSLATIONS.get(lang, {})))
